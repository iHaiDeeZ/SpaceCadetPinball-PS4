#!/usr/bin/env python3
"""The package's Timidity config (/app0/timidity/timidity.cfg) from Debian's freepats.cfg.

Freepats has 70-odd of the 128 General MIDI instruments. A program it lacks is silent in Timidity, so
each missing one is filled with the nearest instrument of its GM family (8 programs each), else with
the nearest one at all. 3D Pinball's PINBALL.MID needs Vibraphone (11): Celesta/Glockenspiel stand in.

    python3 scripts/ps4/make_timidity_cfg.py <freepats.cfg> <out.cfg>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
lines = open(src).read().splitlines()

tones, drums, section = {}, [], None
for line in lines:
    s = line.strip()
    if s.startswith("bank 0"):
        section = "bank"
        continue
    if s.startswith("drumset 0"):
        section = "drum"
        continue
    m = re.match(r"^(\d+)\s+(\S+.*)$", s)
    if not m:
        continue
    if section == "bank":
        tones[int(m.group(1))] = m.group(2)
    elif section == "drum":
        drums.append(f" {m.group(1)}\t{m.group(2)}")

have = sorted(tones)
filled = {}
for p in range(128):
    if p in tones:
        continue
    family = [q for q in have if q // 8 == p // 8]
    pool = family or have
    filled[p] = min(pool, key=lambda q: (abs(q - p), q))

with open(out, "w") as f:
    f.write("# Space Cadet Pinball for PS4: freepats (GPL, see COPYING.freepats), gaps filled by family\n")
    f.write("# generated by scripts/ps4/make_timidity_cfg.py\n")
    f.write("dir /app0/timidity\n\n")
    f.write("drumset 0\n")
    f.write("\n".join(drums) + "\n\n")
    f.write("bank 0\n")
    for p in range(128):
        if p in tones:
            f.write(f" {p}\t{tones[p]}\n")
        else:
            # (on its own line: SDL_mixer's Timidity fails the whole file on a trailing comment)
            f.write(f"# {p}: stand-in, program {filled[p]}\n {p}\t{tones[filled[p]]}\n")
print(f"{len(tones)} instruments, {len(filled)} filled, {len(drums)} drums -> {out}")
